import { readFileSync, writeFileSync } from 'node:fs';

function sqlStr(v) {
  if (v === null || v === undefined) return 'null';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const regions = JSON.parse(readFileSync('supabase/seed-data/regions.json', 'utf-8'));
const countries = JSON.parse(readFileSync('supabase/seed-data/countries.json', 'utf-8'));
const cities = JSON.parse(readFileSync('supabase/seed-data/cities.json', 'utf-8'));

let sql = '-- Generated by scripts/generate-seed-sql.mjs -- do not edit by hand\n\n';

sql += 'insert into regions (code, name_ja, name_en) values\n';
sql += regions
  .map((r) => `  (${sqlStr(r.code)}, ${sqlStr(r.name_ja)}, ${sqlStr(r.name_en)})`)
  .join(',\n');
sql += ';\n\n';

sql += 'insert into countries (iso_code, name_ja, name_en, region_id, sub_region, difficulty, is_un_member) values\n';
sql += countries
  .map(
    (c) =>
      `  (${sqlStr(c.iso_code)}, ${sqlStr(c.name_ja)}, ${sqlStr(c.name_en)}, (select id from regions where code = ${sqlStr(c.region_code)}), ${sqlStr(c.sub_region)}, ${c.difficulty}, ${c.is_un_member})`
  )
  .join(',\n');
sql += ';\n\n';

sql += 'insert into cities (country_id, name_ja, name_en, tier) values\n';
sql += cities
  .map(
    (c) =>
      `  ((select id from countries where iso_code = ${sqlStr(c.country_iso)}), ${sqlStr(c.name_ja)}, ${sqlStr(c.name_en)}, ${sqlStr(c.tier)})`
  )
  .join(',\n');
sql += ';\n';

writeFileSync('supabase/migrations/0002_seed_data.sql', sql);
console.log('wrote supabase/migrations/0002_seed_data.sql');
